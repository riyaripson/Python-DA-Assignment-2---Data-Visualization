# Python DA Assignment 2 - Data Visualization
# Dataset: Seaborn Taxis Dataset

import pandas as pd
import numpy as np
import seaborn as sns
import matplotlib.pyplot as plt

# 1) Loading the Taxis Dataset
df = sns.load_dataset("taxis")

print("First 5 rows:")
print(df.head())
print("Dataset shape:", df.shape)
print("Columns:", df.columns.tolist())
print("Data types:")
print(df.dtypes)

# 2) Handling Missing Values
print("Missing values before treatment:")
print(df.isna().sum())

print("Columns containing missing values:")
print(df.columns[df.isna().any()].tolist())

# Convert timestamps to datetime
df["pickup"] = pd.to_datetime(df["pickup"], errors="coerce")
df["dropoff"] = pd.to_datetime(df["dropoff"], errors="coerce")

# Numerical columns -> median
numeric_cols = df.select_dtypes(include=np.number).columns
for col in numeric_cols:
    df[col] = df[col].fillna(df[col].median())

# Categorical columns -> mode
categorical_cols = df.select_dtypes(include=["object", "category"]).columns
for col in categorical_cols:
    mode_value = df[col].mode(dropna=True)
    if not mode_value.empty:
        df[col] = df[col].fillna(mode_value.iloc[0])

# Pickup time is critical for the line chart, so rows with
# missing/invalid pickup timestamps are removed.
df = df.dropna(subset=["pickup"])

print("Missing values after treatment:")
print(df.isna().sum())
print("Final dataset shape:", df.shape)

# 3A) Matplotlib/Pandas - Line Chart
line_df = df.sort_values("pickup")
plt.figure(figsize=(12, 5))
plt.plot(line_df["pickup"], line_df["fare"], linewidth=1)
plt.title("Fare Over Time")
plt.xlabel("Pickup Timestamp")
plt.ylabel("Fare")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# 3B) Bar Chart - Total Fare by Pickup Borough
borough_fare = (
    df.groupby("pickup_borough", observed=True)["fare"]
      .sum()
      .sort_values(ascending=False)
)
plt.figure(figsize=(9, 5))
borough_fare.plot(kind="bar")
plt.title("Total Fare by Pickup Borough")
plt.xlabel("Pickup Borough")
plt.ylabel("Total Fare")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# 3C) Pie Chart - Trip Distribution by Payment Method
payment_counts = df["payment"].value_counts()
plt.figure(figsize=(7, 7))
plt.pie(
    payment_counts.values,
    labels=payment_counts.index,
    autopct="%1.1f%%",
    startangle=90
)
plt.title("Trip Distribution by Payment Method")
plt.tight_layout()
plt.show()

# 3D) Histogram - Distance Distribution
plt.figure(figsize=(9, 5))
plt.hist(df["distance"], bins=30, edgecolor="black")
plt.title("Distribution of Trip Distance")
plt.xlabel("Distance")
plt.ylabel("Number of Trips")
plt.tight_layout()
plt.show()

# 3E) Box Plot - Tip Distribution by Pickup Borough
plt.figure(figsize=(10, 6))
df.boxplot(column="tip", by="pickup_borough", grid=False)
plt.title("Tip Distribution by Pickup Borough")
plt.suptitle("")
plt.xlabel("Pickup Borough")
plt.ylabel("Tip")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# 3F) Seaborn - Count Plot
plt.figure(figsize=(9, 5))
sns.countplot(
    data=df,
    x="pickup_borough",
    order=df["pickup_borough"].value_counts().index
)
plt.title("Number of Trips by Pickup Borough")
plt.xlabel("Pickup Borough")
plt.ylabel("Number of Trips")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()

# 3G) Seaborn - Scatter Plot
plt.figure(figsize=(10, 6))
sns.scatterplot(
    data=df,
    x="distance",
    y="fare",
    hue="pickup_borough",
    alpha=0.6
)
plt.title("Relationship Between Distance and Fare")
plt.xlabel("Distance")
plt.ylabel("Fare")
plt.tight_layout()
plt.show()

# 3H) Seaborn - Heatmap
corr_cols = ["distance", "fare", "tip", "tolls", "total"]
correlation_matrix = df[corr_cols].corr()

plt.figure(figsize=(8, 6))
sns.heatmap(
    correlation_matrix,
    annot=True,
    cmap="coolwarm",
    fmt=".2f",
    linewidths=0.5
)
plt.title("Correlation Heatmap of Taxi Variables")
plt.tight_layout()
plt.show()

# 3I) Seaborn - Pair Plot
pair_cols = ["distance", "fare", "tip", "total", "pickup_zone"]
pair_df = df[pair_cols].dropna()

# Sample for readability/performance if necessary
if len(pair_df) > 3000:
    pair_df = pair_df.sample(3000, random_state=42)

sns.pairplot(
    pair_df,
    vars=["distance", "fare", "tip", "total"],
    hue="pickup_zone",
    diag_kind="hist"
)
plt.suptitle(
    "Pairwise Relationships: Distance, Fare, Tip and Total",
    y=1.02
)
plt.show()

# 3J) Seaborn - Violin Plot
plt.figure(figsize=(9, 6))
sns.violinplot(
    data=df,
    x="payment",
    y="fare",
    inner="quartile"
)
plt.title("Fare Distribution by Payment Method")
plt.xlabel("Payment Method")
plt.ylabel("Fare")
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()